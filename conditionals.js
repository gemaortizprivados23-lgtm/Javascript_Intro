// Ejercicio: Verificar si una persona aprueba o reprueba

let nota = 6; 
// Declaro la nota del estudiante

if (nota >= 6) { 
  // Si la nota es mayor o igual a 6
  console.log('Aprobado'); 
  // Muestra que aprobó
} else { 
  // Si la nota es menor a 6
  console.log('Reprobado'); 
  // Muestra que no aprobó
}