// Ejercicio: Comparar dos valores usando operadores de comparación

let a = 10; 
// Declaro una variable con valor 10

let b = 5; 
// Declaro otra variable con valor 5

// Comparación de igualdad
console.log(a == b); 
// Verifica si a es igual a b (solo valor)

// Comparación estricta
console.log(a === b); 
// Verifica si son iguales en valor y tipo

// Mayor que
console.log(a > b); 
// Verifica si a es mayor que b

// Menor que
console.log(a < b); 
// Verifica si a es menor que b

// Mayor o igual que
console.log(a >= b); 
// Verifica si a es mayor o igual que b

// Menor o igual que
console.log(a <= b); 
// Verifica si a es menor o igual que b